import { ReviewResult, Severity } from '../types.js';

function getSeverityEmoji(sev: Severity): string {
  switch (sev) {
    case 'critical': return '🔴 **CRITICAL**';
    case 'major': return '🟠 **MAJOR**';
    case 'minor': return '🟡 **MINOR**';
    case 'suggestion': return '🔵 **SUGGESTION**';
  }
}

function getGradeBadgeMarkdown(grade: string, score: number): string {
  const color = score >= 85 ? 'brightgreen' : score >= 70 ? 'yellow' : score >= 50 ? 'orange' : 'red';
  return `![Score](https://img.shields.io/badge/Quality_Score-${score}%2F100-${color}?style=for-the-badge) ![Grade](https://img.shields.io/badge/Grade-${grade}-${color}?style=for-the-badge)`;
}

export function formatMarkdownReport(result: ReviewResult): string {
  const s = result.score;
  const stats = result.stats;

  const lines: string[] = [];

  lines.push(`## ⚡ RevAI Code Review Report`);
  lines.push('');
  lines.push(getGradeBadgeMarkdown(s.grade, s.overall));
  lines.push('');
  lines.push(`> **${s.status}**: ${s.summary}`);
  lines.push('');
  lines.push(`### 📋 Review Summary`);
  lines.push(`| Metric | Value |`);
  lines.push(`| :--- | :--- |`);
  lines.push(`| **Target** | \`${result.targetDescription}\` |`);
  lines.push(`| **Files Audited** | \`${stats.filesChanged} file(s)\` |`);
  lines.push(`| **Lines Changed** | \`+${stats.additions}\` / \`-${stats.deletions}\` |`);
  lines.push(`| **Languages** | \`${stats.languagesDetected.join(', ').toUpperCase() || 'MULTI'}\` |`);
  lines.push(`| **Preloaded Rules Audited** | \`${stats.rulesCheckedCount} rules\` |`);
  lines.push(`| **Total Issues** | **${result.issues.length}** |`);
  lines.push('');

  lines.push(`### 📊 Category Scores`);
  lines.push(`| Category | Score | Issues Found | Status |`);
  lines.push(`| :--- | :---: | :---: | :--- |`);
  lines.push(`| 🛡️ **Security** | \`${s.security.score}%\` | ${s.security.issuesCount} | ${s.security.score >= 80 ? '✅ Pass' : '⚠️ Attention'} |`);
  lines.push(`| ⚡ **Performance** | \`${s.performance.score}%\` | ${s.performance.issuesCount} | ${s.performance.score >= 80 ? '✅ Pass' : '⚠️ Attention'} |`);
  lines.push(`| 🐛 **Reliability & Bugs** | \`${s.reliability.score}%\` | ${s.reliability.issuesCount} | ${s.reliability.score >= 80 ? '✅ Pass' : '⚠️ Attention'} |`);
  lines.push(`| 🧹 **Clean Code & Maintainability** | \`${s.maintainability.score}%\` | ${s.maintainability.issuesCount} | ${s.maintainability.score >= 80 ? '✅ Pass' : '⚠️ Attention'} |`);
  lines.push(`| 📐 **Language Rules Adherence** | \`${s.rulesAdherence.score}%\` | ${s.rulesAdherence.issuesCount} | ${s.rulesAdherence.score >= 80 ? '✅ Pass' : '⚠️ Attention'} |`);
  lines.push('');

  if (result.positiveHighlights && result.positiveHighlights.length > 0) {
    lines.push(`### ✨ Highlights & Strengths`);
    for (const h of result.positiveHighlights) {
      lines.push(`- ✅ ${h}`);
    }
    lines.push('');
  }

  lines.push(`### 🔍 Issues & Recommended Fixes (${result.issues.length})`);
  lines.push('');

  if (result.issues.length === 0) {
    lines.push(`🎉 **Clean Diff!** No critical defects or rule violations were found.`);
  } else {
    result.issues.forEach((issue, idx) => {
      const lineRange = issue.lineStart ? `:${issue.lineStart}${issue.lineEnd ? `-${issue.lineEnd}` : ''}` : '';
      lines.push(`<details ${issue.severity === 'critical' || issue.severity === 'major' ? 'open' : ''}>`);
      lines.push(`<summary><b>#${idx + 1} ${getSeverityEmoji(issue.severity)} - ${issue.title}</b> (<code>${issue.file}${lineRange}</code>)</summary>`);
      lines.push('');
      lines.push(`- **Category:** \`${issue.category}\` ${issue.ruleId ? `| **Rule:** \`${issue.ruleId} (${issue.ruleName || ''})\`` : ''}`);
      lines.push(`- **Problem:** ${issue.description}`);
      lines.push(`- **Why it matters:** ${issue.whyItMatters}`);
      lines.push('');

      if (issue.codeSnippet) {
        lines.push(`**Issue Code:**`);
        lines.push('```diff');
        issue.codeSnippet.split('\n').forEach(l => lines.push(`- ${l}`));
        lines.push('```');
      }

      if (issue.fixedCodeSnippet) {
        lines.push(`**Suggested Fix:**`);
        lines.push('```diff');
        issue.fixedCodeSnippet.split('\n').forEach(l => lines.push(`+ ${l}`));
        lines.push('```');
      } else if (issue.suggestedFix) {
        lines.push(`**Solution:** ${issue.suggestedFix}`);
      }

      lines.push('</details>');
      lines.push('');
    });
  }

  lines.push('---');
  lines.push(`*Generated by [RevAI](https://github.com/amrkamal/revai) — 100% Free AI Code Reviewer powered by Google Gemini.*`);

  return lines.join('\n');
}
